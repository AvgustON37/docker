# Commit commands
git add .    # Добавление индексикации
git commit -m "Discription"  # Сделать коммит
git push    # Отправить изменение на отдаленный репизиторий

git pull   # Слить изменения отдаленного репозитория

# Branch commands
git branch -m old-branch new-branch   # Создать новую ветку
git switch    # Переключиться на другую ветку
